/// `cargo test -p ow-package --lib testkit -- --ignored`, then `build/Release/ow-package.exe <file>`.
#[test]
#[ignore = "writes files under local/; run by hand to feed the C++ reader"]
fn write_cases_for_the_cpp_reader() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../local/testkit/rust");
    std::fs::create_dir_all(&dir).expect("create local/testkit/rust");
    let mut props = PackageBuilder::new_empty();
    props.names_utf16(PROPERTY_NAMES);
    let mut payload = ints(&[0]);
    payload.extend_from_slice(&props.int_tag("Test", -42));
    payload.extend_from_slice(&props.str_tag("Test", "hello\u{1F600}"));
    let vector = props.fname("Vector", 0);
    payload.extend_from_slice(&props.tag_detail("Test", "StructProperty", &vector, &[0; 12]));
    payload.extend_from_slice(&props.none());
    let cases: [(&str, Vec<u8>); 6] = [
        ("package_valid.bin", package_valid().build()),
        (
            "package_container.bin",
            container(&package_valid().build(), DEFAULT_BLOCK),
        ),
        ("package_partial.bin", package_valid().build_partial()),
        (
            "properties.bin",
            properties_package(payload, 0, "Child", None),
        ),
        ("B.upk", runtime_b().build()),
        ("A.upk", runtime_a().build()),
    ];
    for (name, bytes) in cases {
        std::fs::write(dir.join(name), bytes).expect("write case");
    }
}

