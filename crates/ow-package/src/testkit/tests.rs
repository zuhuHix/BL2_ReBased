/// `properties_test.py`'s `package(payload, outer, child_name, engine_class)`.
fn properties_package(
    payload: Vec<u8>,
    outer: i32,
    child: &str,
    engine_class: Option<&str>,
) -> Vec<u8> {
    let mut p = PackageBuilder::new_empty();
    p.names_utf16(PROPERTY_NAMES);
    match engine_class {
        None => {
            p.add_import("Root", "Class", 0, "Root");
        }
        Some(class) => {
            p.add_import("Root", "Class", 0, "Engine");
            p.add_import("Engine", "Class", -1, class);
        }
    }
    let class = if engine_class.is_some() { -2 } else { -1 };
    p.add_export_with(Export {
        outer,
        number: 2,
        ..Export::new(class, child, payload)
    });
    p.build()
}

#[test]
fn properties_test_tags_and_utf16_names() {
    let mut p = PackageBuilder::new_empty();
    p.names_utf16(PROPERTY_NAMES);
    let wide = p.fname("Wide\u{1F600}", 3);
    let none = p.fname("None", 0);
    let enum_name = p.fname("Enum", 0);
    let choice = p.fname("Choice", 0);
    let vector = p.fname("Vector", 0);
    let fields = [
        p.tag("Test", "IntProperty", &ints(&[-42])),
        p.tag("Test", "FloatProperty", &1.25f32.to_le_bytes()),
        p.tag_detail("Test", "BoolProperty", &[1], &[]),
        p.tag("Test", "NameProperty", &wide),
        p.tag("Test", "ObjectProperty", &ints(&[-1])),
        p.tag("Test", "ObjectProperty", &ints(&[0])),
        p.tag("Test", "StrProperty", &fstring("hello\u{1F600}\"\n")),
        p.tag_detail("Test", "ByteProperty", &none, &[0x7f]),
        p.tag_detail("Test", "ByteProperty", &enum_name, &choice),
        p.tag_detail("Test", "StructProperty", &vector, &[0; 12]),
        p.tag("Test", "ArrayProperty", &ints(&[2, 11, 22])),
        p.tag("Test", "UnknownProperty", b"opaque"),
        p.tag_full("Quoted\"\\\n", 3, "IntProperty", 4, &[], &ints(&[99])),
    ];
    let mut payload = ints(&[0]);
    for field in fields {
        payload.extend_from_slice(&field);
    }
    payload.extend_from_slice(&none);
    same(
        &properties_package(payload, 0, "Child", None),
        PROPERTIES_FIELDS,
    );
}

