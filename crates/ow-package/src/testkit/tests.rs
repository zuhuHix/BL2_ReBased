//! Owner: lane W1-TESTKIT. Pins the testkit's bytes to the Python fixture helpers in `tests/`.
//!
//! Each case builds, with invented inputs, the same package one helper builds. The expected bytes at the bottom of
//! this file were produced by running the helpers themselves (their definitions loaded from `tests/*.py`, no test
//! body run) on those inputs, locally, on 2026-11-15; they contain no game data. A case that differs here means the
//! testkit no longer writes what the Python tests write.

use super::*;

fn hex(parts: &[&str]) -> Vec<u8> {
    let text: String = parts.concat();
    assert_eq!(text.len() % 2, 0);
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&text[i..i + 2], 16).expect("hex digit"))
        .collect()
}

fn fnv1a64(data: &[u8]) -> u64 {
    data.iter().fold(0xcbf2_9ce4_8422_2325, |h, &b| {
        (h ^ u64::from(b)).wrapping_mul(0x0000_0100_0000_01b3)
    })
}

#[track_caller]
fn same(actual: &[u8], expected: &[&str]) {
    let expected = hex(expected);
    if let Some(at) = actual.iter().zip(&expected).position(|(a, b)| a != b) {
        panic!(
            "first difference at byte {at}: {:#04x} here, {:#04x} from Python",
            actual[at], expected[at]
        );
    }
    assert_eq!(
        actual.len(),
        expected.len(),
        "same prefix, different length"
    );
}

#[track_caller]
fn same_hash(actual: &[u8], (len, hash): (usize, u64)) {
    assert_eq!(actual.len(), len);
    assert_eq!(fnv1a64(actual), hash);
}

